import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { svelte } from '@sveltejs/vite-plugin-svelte';
import { build } from 'vite';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(webRoot, 'admin-data-list-preview.html');
const temporaryOutput = await mkdtemp(join(tmpdir(), 'well-ambient-admin-data-list-preview-'));

try {
  await build({
    configFile: false,
    root: webRoot,
    plugins: [svelte()],
    logLevel: 'warn',
    build: {
      outDir: temporaryOutput,
      emptyOutDir: true,
      cssCodeSplit: false,
      lib: {
        entry: resolve(webRoot, 'src/admin-data-list-preview-entry.ts'),
        formats: ['iife'],
        name: 'WellAmbientAdminDataListPreview',
        fileName: () => 'admin-data-list-preview.js'
      },
      rollupOptions: {
        output: {
          assetFileNames: 'admin-data-list-preview.[ext]'
        }
      }
    }
  });

  const files = await readdir(temporaryOutput);
  const cssFile = files.find((file) => file.endsWith('.css'));
  const javascript = await readFile(resolve(temporaryOutput, 'admin-data-list-preview.js'), 'utf8');
  const css = cssFile ? await readFile(resolve(temporaryOutput, cssFile), 'utf8') : '';
  const safeJavascript = javascript.replace(/<\/script/gi, '<\\/script');

  const html = `<!doctype html>
<html lang="zh-CN">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="color-scheme" content="light" />
    <title>通用列表组件预览</title>
    <!-- Generated by pnpm build:admin-data-list-preview. -->
    <style data-admin-data-list-preview>${css}</style>
  </head>
  <body>
    <div id="admin-data-list-preview"></div>
    <script data-admin-data-list-preview>${safeJavascript}</script>
  </body>
</html>
`;

  await writeFile(outputPath, html, 'utf8');
  console.log(`Generated ${outputPath}`);
} finally {
  await rm(temporaryOutput, { recursive: true, force: true });
}
